    def test_malformed_native_lock_shapes_fail_cleanly(self):
        api = self.api(); p = self.write('[tools]\nkubectl="latest"')
        for raw in ('lockfile_version=4\n[tools]\nkubectl=["bad"]',
                    'lockfile_version=4\n[[tools.kubectl]]\nversion="1"\nbackend="aqua:x"\nspecifiers="latest"'):
            p.with_suffix('.lock').write_text(raw)
            with self.subTest(raw=raw), self.assertRaises(ValueError):
                api.read_user_tools(self.paths, self.env, require_lock=True)

    def test_source_lock_collisions_are_rejected_without_creating_or_changing_profiles(self):
        api = self.api()
        source = self.root / 'custom.lock'
        env = dict(self.env, CLAUDE_MISE_CONFIG_FILE=str(source))
        with self.assertRaisesRegex(ValueError, 'distinct'):
            api.init_user_tools(self.paths, env)
        self.assertFalse(source.exists())
        source.write_bytes(b'[tools]\nkubectl="latest"\n')
        before = source.read_bytes()
        for operation in (lambda: api.resolve_user_tools_paths(self.paths, env),
                          lambda: api.read_user_tools(self.paths, env, require_lock=False)):
            with self.assertRaisesRegex(ValueError, 'distinct'): operation()
            self.assertEqual(source.read_bytes(), before)
        alias = self.root / 'selected.toml'
        lock = alias.with_suffix('.lock')
        lock.write_bytes(before)
        alias.symlink_to(lock)
        alias_env = dict(self.env, CLAUDE_MISE_CONFIG_FILE=str(alias))
        with self.assertRaisesRegex(ValueError, 'distinct'):
            api.resolve_user_tools_paths(self.paths, alias_env)
        self.assertTrue(alias.is_symlink())
        self.assertEqual(lock.read_bytes(), before)

    def test_retention_enumerates_colliding_paths_without_inspecting_profiles(self):
        api = self.api()
        default_source = self.write('deliberately invalid TOML')
        default_lock = default_source.with_suffix('.lock')
        default_source.rename(default_lock)
        default_source.symlink_to(default_lock)
        custom_source = self.root / 'custom.toml'
        custom_lock = self.root / 'custom.lock'
        custom_lock.write_text('also not TOML')
        custom_source.symlink_to(custom_lock)
        defaults = (default_source, default_lock)
        cases = ((self.env, defaults),
                 (dict(self.env, CLAUDE_MISE_CONFIG_FILE=str(custom_source)),
                  defaults + (custom_source, custom_lock)),
                 (dict(self.env, CLAUDE_MISE_CONFIG_FILE=str(custom_lock)),
                  defaults + (custom_lock,)),
                 (dict(self.env, CLAUDE_MISE_CONFIG_FILE='invalid-relative'), defaults))
        # Teardown retention needs path enumeration even when profile reads or
        # filesystem alias validation would fail.
        with patch.object(Path, 'read_bytes', side_effect=AssertionError('profile read')), \
             patch.object(Path, 'resolve', side_effect=AssertionError('alias resolution')), \
             patch.object(Path, 'stat', side_effect=AssertionError('profile stat')):
            for env, expected in cases:
                with self.subTest(selection=env.get('CLAUDE_MISE_CONFIG_FILE')):
                    self.assertEqual(api.retained_user_tools_paths(self.paths, env),
                                     expected + tuple(parent / '.mise/locks' for parent in dict.fromkeys(p.parent for p in expected)))
        for env, _ in cases[:-1]:
            with self.subTest(operation_selection=env.get('CLAUDE_MISE_CONFIG_FILE')):
                with self.assertRaisesRegex(ValueError, 'distinct'):
                    api.read_user_tools(self.paths, env, require_lock=False)
