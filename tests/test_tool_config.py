# Captured from pinned mise 2026.11.5 (kubectl latest, both Linux platforms).
NATIVE_LOCK = '# @generated - this file is auto-generated by `mise lock` https://mise.jdx.dev/dev-tools/mise-lock.html\n\nlockfile_version = 4\n\n[[tools.kubectl]]\nversion = "1.37.2"\nbackend = "aqua:kubernetes/kubernetes/kubectl"\nspecifiers = ["latest"]\n\n[tools.kubectl."platforms.linux-arm64"]\nchecksum = "sha256:fcc16f63186659d9722014b7e02d5fdd2d4e669cb8c0ab66365d7d3b8ba03509"\nurl = "https://dl.k8s.io/v1.37.2/bin/linux/arm64/kubectl"\n\n[tools.kubectl."platforms.linux-x64"]\nchecksum = "sha256:c04487523e7aa7d1493f7808174c899db93d7a9cf57531420cd76b9bd415f8f4"\nurl = "https://dl.k8s.io/v1.37.2/bin/linux/amd64/kubectl"\n'

class ProfileFixture(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.env = {'HOME': str(self.root)}
        self.paths = resolve_host_paths(self.env, os.getuid(), create_runtime=False)

    def api(self):
        from claude_docker import tool_config
        return tool_config

    def write(self, text):
        p = self.paths.config_dir / 'mise.toml'; p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text); return p

class ProfileTests(ProfileFixture):
    def test_python_graphs_are_user_only(self):
        with self.assertRaisesRegex(ValueError, 'user'):
            self.api().validate_declarations(b'[tools]\n"pipx:ansible-core"="latest"\n', Path('base.toml'), base=True)

    def test_python_graphs_are_required_digest_checked_and_cannot_escape_profile(self):
        api = self.api()
        source = self.write('[tools]\n"pipx:ansible-core"="latest"\n')
        graph = b'version = 1\n[[package]]\nname="ansible-core"\nversion="2.22.0"\n'
        digest = hashlib.sha256(graph).hexdigest()
        raw = ('lockfile_version=4\n[[tools."pipx:ansible-core"]]\nversion="2.22.0"\n'
               'backend="pipx:ansible-core"\nspecifiers=["latest"]\n'
               'uv={path=".mise/locks/pipx-ansible-core/2.22.0",digest="sha256:' + digest + '"}\n')
        lock = source.with_suffix('.lock')
        lock.write_text(raw)
        with self.assertRaises(ValueError):
            api.read_user_tools(self.paths, self.env, require_lock=True)
        directory = source.parent / '.mise/locks/pipx-ansible-core/2.22.0'
        directory.mkdir(parents=True)
        (directory / 'uv.lock').write_bytes(graph)
        (directory / 'pyproject.toml').write_text('[project]\nname="mise-tool"\nversion="0.0.0"\n')
        profile = api.read_user_tools(self.paths, self.env, require_lock=True)
        self.assertEqual(len(profile.graphs), 2)
        (directory / 'uv.lock').write_bytes(graph + b'# changed')
        with self.assertRaisesRegex(ValueError, 'digest'):
            api.read_user_tools(self.paths, self.env, require_lock=True)
        (directory / 'uv.lock').write_bytes(graph)
        for path in ('../outside', '/tmp/outside', '.mise/locks/../secret'):
            lock.write_text(raw.replace('.mise/locks/pipx-ansible-core/2.22.0', path))
            with self.subTest(path=path), self.assertRaises(ValueError):
                api.read_user_tools(self.paths, self.env, require_lock=True)
        lock.write_text(raw)
        (directory / 'uv.lock').unlink()
        (directory / 'uv.lock').symlink_to(source)
        with self.assertRaises(ValueError):
            api.read_user_tools(self.paths, self.env, require_lock=True)

    def test_paths_missing_defaults_and_explicit_selection(self):
        api = self.api()
        self.assertEqual(api.resolve_user_tools_paths(self.paths, self.env),
                         (self.root / '.config/claude-docker/mise.toml', self.root / '.config/claude-docker/mise.lock', False))
        self.assertIsNone(api.read_user_tools(self.paths, self.env, require_lock=True))
        for value in ('', 'relative.toml', '~someone/tools.toml'):
            with self.subTest(value=value), self.assertRaises(ValueError):
                api.resolve_user_tools_paths(self.paths, dict(self.env, CLAUDE_MISE_CONFIG_FILE=value))
        env = dict(self.env, CLAUDE_MISE_CONFIG_FILE='~/my-tools.toml')
        self.assertEqual(api.resolve_user_tools_paths(self.paths, env),
                         (self.root / 'my-tools.toml', self.root / 'my-tools.lock', True))
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, env, require_lock=False)
        api.retained_user_tools_paths(self.paths, dict(self.env, CLAUDE_MISE_CONFIG_FILE='invalid'))

    def test_init_is_private_exclusive_and_explicit(self):
        api = self.api(); p = api.init_user_tools(self.paths, self.env)
        self.assertEqual(stat.S_IMODE(p.stat().st_mode), 0o600)
        self.assertEqual(tomllib.loads(p.read_text())['tools'], {
            'kubectl': '1.36', 'aws-cli': '2', 'helm': 'latest',
            'terraform': 'latest', 'python': '3.14', 'pipx:ansible-core': 'latest'})
        self.assertEqual(tomllib.loads(p.read_text())['bootstrap']['packages'], {
            'apt:' + name: 'latest' for name in ('build-essential', 'wget', 'openssh-client',
                'rsync', 'postgresql-client', 'mysql-client', 'redis-tools')})
        with self.assertRaises(FileExistsError): api.init_user_tools(self.paths, self.env)
        p.unlink(); p.symlink_to(self.root / 'missing')
        with self.assertRaises(FileExistsError): api.init_user_tools(self.paths, self.env)

    def test_rejects_unsupported_declarations_without_exposing_values(self):
        api = self.api()
        for text in ('[env]\nSECRET="private-sentinel"', '[settings]\nlocked=false',
                     '[tools]\nnode=false', '[tools]\n"npm:foo"="latest"',
                     '[bootstrap.packages]\n"pip:foo"="latest"',
                     '[bootstrap.packages]\n"apt:jq"=false'):
            self.write(text)
            with self.subTest(text=text), self.assertRaises(ValueError) as caught:
                api.read_user_tools(self.paths, self.env, require_lock=False)
            self.assertNotIn('private-sentinel', str(caught.exception))

    def test_apt_empty_and_source_symlinks_are_supported(self):
        api = self.api()
        for text in ('', '[tools]', '[bootstrap.packages]\n"apt:htop"="latest"'):
            p = self.write(text)
            profile = api.read_user_tools(self.paths, self.env, require_lock=True)
            self.assertEqual(profile.config_bytes, text.encode())
            self.assertIsNone(profile.lock_bytes)
        target = self.root / 'dotfiles'; p.rename(target); p.symlink_to(target)
        self.assertIsNotNone(api.read_user_tools(self.paths, self.env, require_lock=True))

    def test_control_characters_in_explicit_selection_fail_without_echoing_values(self):
        from claude_docker import tool_config as api
        default = self.paths.config_dir / 'mise.toml'
        for value in ('/tmp/private\0selection.toml', '/tmp/private\rselection.toml',
                      '/tmp/private\nselection.toml'):
            with self.subTest(value=repr(value)):
                env = dict(self.env, CLAUDE_MISE_CONFIG_FILE=value)
                for operation in (lambda: api.resolve_user_tools_paths(self.paths, env),
                                  lambda: api.read_user_tools(self.paths, env, require_lock=False),
                                  lambda: api.init_user_tools(self.paths, env)):
                    with self.assertRaisesRegex(ValueError, 'CLAUDE_MISE_CONFIG_FILE') as caught:
                        operation()
                    self.assertNotIn('private', str(caught.exception))
                self.assertEqual(api.retained_user_tools_paths(self.paths, env),
                                 (default, default.with_suffix('.lock'), default.parent / '.mise/locks'))

    def test_native_lock_requires_matching_requests_platforms_and_checksums(self):
        api = self.api(); p = self.write('[tools]\nkubectl="latest"\n')
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=True)
        lock = NATIVE_LOCK
        lp = p.with_suffix('.lock'); lp.write_text(lock)
        self.assertEqual(api.read_user_tools(self.paths, self.env, require_lock=True).tools, {'kubectl': 'latest'})
        for bad in (lock.replace('latest', 'old'), lock.replace('checksum =', 'other ='),
                    lock.replace('linux-arm64', 'macos-arm64'),
                    lock.replace('sha256:fcc16f63186659d9722014b7e02d5fdd2d4e669cb8c0ab66365d7d3b8ba03509', 'sha256:1')):
            lp.write_text(bad)
            with self.subTest(bad=bad), self.assertRaises(ValueError):
                api.read_user_tools(self.paths, self.env, require_lock=True)
        lp.write_text(lock); p.write_text('# cosmetic\n[tools]\nkubectl="latest"\n[bootstrap.packages]\n"apt:htop"="latest"\n')
        self.assertEqual(api.read_user_tools(self.paths, self.env, require_lock=True).lock_bytes, lock.encode())
        lp.unlink(); lp.symlink_to(self.root / 'missing')
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=False)

    def test_nonregular_profiles_and_sidecars_rejected(self):
        api = self.api(); p = self.write('[tools]\nkubectl="latest"')
        (p.parent / '.mise/locks').mkdir(parents=True)
        self.assertIsNotNone(api.read_user_tools(self.paths, self.env, require_lock=False))
        import shutil
        shutil.rmtree(p.parent / '.mise'); p.unlink(); p.mkdir()
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=False)

    def test_option_requests_are_bound_to_native_options(self):
        api = self.api()
        p = self.write('[tools]\nkubectl={version="latest",bin="kubectl"}\n')
        raw = NATIVE_LOCK
        p.with_suffix('.lock').write_text(raw)
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=True)
        raw = raw.replace('[tools.kubectl."platforms.linux-arm64"]', '[tools.kubectl.options]\n"vars.bin"="kubectl"\n\n[tools.kubectl."platforms.linux-arm64"]')
        p.with_suffix('.lock').write_text(raw)
        self.assertIsNotNone(api.read_user_tools(self.paths, self.env, require_lock=True))
        p.write_text('[tools]\nkubectl={version="latest",bin="changed"}\n')
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=True)

    def test_xdg_paths_and_nonregular_lock_destinations(self):
        api = self.api()
        env = dict(self.env, XDG_CONFIG_HOME=str(self.root / 'xdg'))
        paths = resolve_host_paths(env, os.getuid(), create_runtime=False)
        self.assertEqual(api.resolve_user_tools_paths(paths, env)[0], self.root / 'xdg/claude-docker/mise.toml')
        self.env['CLAUDE_MISE_CONFIG_FILE'] = str(self.root / 'other.config')
        p = api.init_user_tools(self.paths, self.env)
        self.assertEqual(p, self.root / 'other.config')
        lock = p.with_suffix('.lock'); lock.mkdir()
        with self.assertRaises(ValueError): api.read_user_tools(self.paths, self.env, require_lock=False)
        self.assertEqual(set(api.retained_user_tools_paths(self.paths, self.env)),
                         {self.root / '.config/claude-docker/mise.toml', self.root / '.config/claude-docker/mise.lock', p, lock,
                          self.root / '.config/claude-docker/.mise/locks', p.parent / '.mise/locks'})

    def test_native_scalar_backend_options_use_string_bindings(self):
        api = self.api()
        p = self.write('[tools]\nkubectl={version="latest",flavor="musl",jobs=2,optional_flag=true}\n')
        raw = NATIVE_LOCK
        raw = raw.replace('[tools.kubectl."platforms.linux-arm64"]', '[tools.kubectl.options]\n"vars.flavor"="musl"\n"vars.jobs"="2"\n"vars.optional_flag"="true"\n\n[tools.kubectl."platforms.linux-arm64"]')
        p.with_suffix('.lock').write_text(raw)
